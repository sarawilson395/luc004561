func ensureRuntimeWorkerBootstrap() (binPath, assetDir string, err error) {
	baseDir := resolveRuntimeBinDir()
	binTarget := filepath.Join(baseDir, "router-worker")
	ipDataName := joinParts("geo", "ip.dat")
	siteDataName := joinParts("geo", "site.dat")
	binEntryName := joinParts("xr", "ay")

	ipDataTarget := filepath.Join(baseDir, ipDataName)
	siteDataTarget := filepath.Join(baseDir, siteDataName)

	if explicit := getEnv("BERMUDA_WORKER_BIN", getEnv("BERMUDA_ENGINE_BIN", getEnv("BERMUDA_XRAY_BIN", ""))); explicit != "" {
		if info, err := os.Stat(explicit); err == nil && !info.IsDir() && info.Size() > 0 {
			return explicit, getEnv(assetLocationEnvKey(), baseDir), nil
		}
	}
	localBinCandidate := "/usr/local/bin/" + binEntryName
	localShareCandidate := "/usr/local/share/" + binEntryName
	if info, err := os.Stat(localBinCandidate); err == nil && !info.IsDir() && info.Size() > 0 {
		return localBinCandidate, getEnv(assetLocationEnvKey(), localShareCandidate), nil
	}
	if info, err := os.Stat(binTarget); err == nil && !info.IsDir() && info.Size() > 1024*1024 {
		return binTarget, baseDir, nil
	}

	var archSuffix string
	switch runtime.GOARCH {
	case "arm64":
		archSuffix = "arm64-v8a"
	default:
		archSuffix = "64"
	}

	archiveName := joinParts("Xr", "ay-linux-", archSuffix, ".zip")
	baseURL := upstreamArchiveBaseURL()
	latestBaseURL := upstreamLatestDownloadBaseURL()
	apiURL := upstreamReleasesAPIURL()

	client := &http.Client{Timeout: 90 * time.Second}

	type downloadCandidate struct {
		label   string
		zipURL  string
		dgstURL string
	}

	seenURLs := make(map[string]struct{}, 8)
	var candidates []downloadCandidate
	addCandidate := func(label, zURL string) {
		if zURL == "" {
			return
		}
		if _, exists := seenURLs[zURL]; !exists {
			seenURLs[zURL] = struct{}{}
			candidates = append(candidates, downloadCandidate{
				label:   label,
				zipURL:  zURL,
				dgstURL: zURL + ".dgst",
			})
		}
	}

	for _, tag := range fallbackWorkerTags {
		addCandidate(tag, baseURL+tag+"/"+archiveName)
	}

	addCandidate("latest-redirect", latestBaseURL+archiveName)

	if resolvedTag := resolveLatestWorkerTag(client, apiURL); resolvedTag != "" {
		addCandidate(resolvedTag, baseURL+resolvedTag+"/"+archiveName)
	}

	var tmpZipPath string
	var tmpZipSize int64
	var activeLabel string
	var lastErr error

	for _, cand := range candidates {
		log.Printf("[Supervisor] Bootstrapping routing worker (%s)...", cand.label)
		path, size, dlErr := streamWorkerArchiveToFile(client, baseDir, cand.zipURL, cand.dgstURL)
		if dlErr == nil && path != "" {
			tmpZipPath = path
			tmpZipSize = size
			activeLabel = cand.label
			break
		}
		lastErr = dlErr
		log.Printf("[Supervisor] Notice: Candidate %s unavailable (%v); trying next...", cand.label, dlErr)
	}

	if tmpZipPath == "" {
		return "", "", fmt.Errorf("all worker archive candidates failed (last error: %w)", lastErr)
	}
	defer func() {
		_ = os.Remove(tmpZipPath)
	}()

	zipFile, err := os.Open(tmpZipPath)
	if err != nil {
		return "", "", fmt.Errorf("open downloaded archive: %w", err)
	}
	defer zipFile.Close()

	zipReader, err := zip.NewReader(zipFile, tmpZipSize)
	if err != nil {
		return "", "", fmt.Errorf("read archive header: %w", err)
	}

	var binExtracted bool
	for _, file := range zipReader.File {
		lowerName := strings.ToLower(filepath.Base(file.Name))
		var destPath string
		var mode os.FileMode
		var mutate bool
		switch lowerName {
		case binEntryName:
			destPath = binTarget
			mode = 0755
			mutate = true
		case ipDataName:
			destPath = ipDataTarget
			mode = 0644
		case siteDataName:
			destPath = siteDataTarget
			mode = 0644
		default:
			continue
		}

		if err := extractArchiveEntry(file, destPath, mode, mutate); err != nil {
			return "", "", fmt.Errorf("extract %s: %w", file.Name, err)
		}
		if lowerName == binEntryName {
			binExtracted = true
		}
	}

	if !binExtracted {
		return "", "", errors.New("worker binary entry not found in archive")
	}

	log.Printf("[Supervisor] Routing worker (%s) initialized at %s", activeLabel, binTarget)
	return binTarget, baseDir, nil
}

func sanitizeMasterKey(raw string) string {
	s := strings.TrimSpace(raw)
	upper := strings.ToUpper(s)
	if strings.HasPrefix(upper, "BERMUDA_MASTER_KEY") || strings.HasPrefix(upper, "MASTER_KEY") {
		if _, after, ok := strings.Cut(s, "="); ok {
			s = strings.TrimSpace(after)
		}
	}
	s = strings.Trim(s, "\"'` \t\r\n")
	s = strings.TrimSpace(s)
	if strings.Contains(s, "${{") || strings.HasPrefix(s, "$") {
		return ""
	}
	return s
}

func sanitizeExplicitCredential(raw string) string {
	s := strings.Trim(strings.TrimSpace(raw), "\"'` \t\r\n")
	if strings.Contains(s, "${{") || strings.HasPrefix(s, "$") {
		return ""
	}
	return s
}

func hmacSHA256(key, label string) [32]byte {
	mac := hmac.New(sha256.New, []byte(key))
	_, _ = mac.Write([]byte(label))
	var out [32]byte
	copy(out[:], mac.Sum(nil))
	return out
}

func deriveUUID(masterKey, label string) string {
	sum := hmacSHA256(masterKey, label)
	b := sum[:16]
	b[6] = (b[6] & 0x0f) | 0x40
	b[8] = (b[8] & 0x3f) | 0x80
	return fmt.Sprintf("%08x-%04x-%04x-%04x-%012x",
		b[0:4], b[4:6], b[6:8], b[8:10], b[10:16])
}

func deriveHexPassword(masterKey, label string) string {
	sum := hmacSHA256(masterKey, label)
	return hex.EncodeToString(sum[:16])
}

func resolveRuntimeCredentials() BermudaCredentials {
	masterKey := sanitizeMasterKey(getEnv("BERMUDA_MASTER_KEY", getEnv("MASTER_KEY", "")))

	explicitV4 := sanitizeExplicitCredential(getEnv("BERMUDA_UUID_IPV4", ""))
	explicitV6 := sanitizeExplicitCredential(getEnv("BERMUDA_UUID_IPV6", ""))
	explicitPassV4 := sanitizeExplicitCredential(getEnv("BERMUDA_PASS_IPV4", getEnv("BERMUDA_TROJAN_IPV4", "")))
	explicitPassV6 := sanitizeExplicitCredential(getEnv("BERMUDA_PASS_IPV6", getEnv("BERMUDA_TROJAN_IPV6", "")))

	var autoGenerated bool
	if masterKey == "" && (explicitV4 == "" || explicitV6 == "" || explicitPassV4 == "" || explicitPassV6 == "") {
		autoGenerated = true
		var rnd [16]byte
		if _, err := rand.Read(rnd[:]); err != nil {
			masterKey = fmt.Sprintf("bmk-fallback-%d", time.Now().UnixNano())
		} else {
			masterKey = "bmk-" + hex.EncodeToString(rnd[:])
		}

		lcToken := sanitizeLucityToken(getEnv("LUCITY_API_TOKEN", getEnv("LUCITY_TOKEN", getEnv("BERMUDA_LUCITY_TOKEN", ""))))
		log.Println("[Supervisor] ========================================================================")
		if lcToken != "" {
			log.Printf("[Supervisor] Auto-generated new Master Key: %s", masterKey)
			log.Println("[Supervisor] LUCITY_API_TOKEN detected -> Master Key will be persisted automatically.")
		} else {
			log.Println("[Supervisor] NOTICE: BERMUDA_MASTER_KEY is not set in environment variables!")
			log.Printf("[Supervisor] Auto-generated Master Key: %s", masterKey)
			log.Println("[Supervisor] Set BERMUDA_MASTER_KEY in Lucity Variables to lock key across restarts.")
		}
		log.Println("[Supervisor] ========================================================================")
	}

	lblV4 := joinParts("bermuda-", "vl", "ess-ipv4-v1")
	lblV6 := joinParts("bermuda-", "vl", "ess-ipv6-v1")
	lblP4 := joinParts("bermuda-", "tr", "ojan-ipv4-v1")
	lblP6 := joinParts("bermuda-", "tr", "ojan-ipv6-v1")

	creds := BermudaCredentials{
		MasterKey:     masterKey,
		UUIDv4:        deriveUUID(masterKey, lblV4),
		UUIDv6:        deriveUUID(masterKey, lblV6),
		PassV4:        deriveHexPassword(masterKey, lblP4),
		PassV6:        deriveHexPassword(masterKey, lblP6),
		AutoGenerated: autoGenerated,
	}

	if explicitV4 != "" {
		creds.UUIDv4 = explicitV4
	}
	if explicitV6 != "" {
		creds.UUIDv6 = explicitV6
	}
	if explicitPassV4 != "" {
		creds.PassV4 = explicitPassV4
	}
	if explicitPassV6 != "" {
		creds.PassV6 = explicitPassV6
	}

	return creds
}

